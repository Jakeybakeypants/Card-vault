#!/usr/bin/env node
// Regenerates src/games/pokemonSets.ts from a checkout of https://github.com/tcgdex/cards-database
// (MIT). Set files plus the card file names are read (card contents are not):
//
//   git clone --depth 1 --filter=blob:none --sparse https://github.com/tcgdex/cards-database
//   cd cards-database && git sparse-checkout set --no-cone '/data/*/*.ts'
//   node scripts/gen-pokemon-sets.mjs ../cards-database
//
// The app still reads the live set list from TCGdex; this table adds what that list lacks:
// printed set codes (SVI, PAL, BRS:TG…), release dates and series.
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) {
  console.error('usage: node scripts/gen-pokemon-sets.mjs <path to tcgdex/cards-database>');
  process.exit(1);
}

const data = join(root, 'data');
// Card ids per set folder, from git so a blobless clone needs no card contents.
const files = execFileSync('git', ['-C', root, 'ls-tree', '-r', '--name-only', 'HEAD', 'data'], { encoding: 'utf8', maxBuffer: 64 << 20 }).split('\n');
const idsByFolder = new Map();
for (const f of files) {
  const m = /^data\/(.+)\/([^/]+)\.ts$/.exec(f);
  if (!m || !m[1].includes('/')) continue;
  idsByFolder.set(m[1], [...(idsByFolder.get(m[1]) ?? []), m[2]]);
}
/** How TCGdex pads this set's numbers: 3 for "001", 2 for "TG01", 0 for "1". */
function padding(ids) {
  let width = 0;
  for (const id of ids) {
    const digits = /^[A-Z]*(\d+)[a-z]?$/i.exec(id)?.[1];
    if (digits && digits.length > 1 && digits.startsWith('0')) width = Math.max(width, digits.length);
  }
  return width;
}
const rows = [];
for (const serie of readdirSync(data)) {
  const dir = join(data, serie);
  // TCG Pocket is the mobile game: no physical cards.
  if (!statSync(dir).isDirectory() || serie === 'Pokémon TCG Pocket') continue;
  for (const file of readdirSync(dir)) {
    if (!file.endsWith('.ts')) continue;
    const src = readFileSync(join(dir, file), 'utf8');
    const id = /\bid:\s*"([^"]+)"/.exec(src)?.[1];
    const name = /name:\s*\{[^}]*?\ben:\s*"([^"]+)"/s.exec(src)?.[1];
    const official = Number(/official:\s*(\d+)/.exec(src)?.[1] ?? NaN);
    const date = /releaseDate:\s*"([^"]+)"/.exec(src)?.[1];
    const code = /abbreviations:\s*\{[^}]*?official:\s*"([^"]+)"/s.exec(src)?.[1] ?? '';
    if (!id || !name || !Number.isFinite(official) || !date) continue;
    rows.push([id, name, official, code, date, serie, padding(idsByFolder.get(`${serie}/${file.slice(0, -3)}`) ?? [])]);
  }
}
rows.sort((a, b) => b[4].localeCompare(a[4]) || a[0].localeCompare(b[0]));

const body = rows.map((r) => `  ${JSON.stringify(r)},`).join('\n');
writeFileSync(
  new URL('../src/games/pokemonSets.ts', import.meta.url),
  `// Generated by scripts/gen-pokemon-sets.mjs from tcgdex/cards-database (MIT). Do not edit.
// [TCGdex set id, English name, printed set size, printed set code, release date, series,
//  zero-padding of TCGdex card ids (3 = "001", 0 = "1")]
export type PokemonSetRow = [id: string, name: string, official: number, code: string, releaseDate: string, series: string, pad: number];

export const POKEMON_SETS: PokemonSetRow[] = [
${body}
];
`,
);
console.log(`wrote ${rows.length} sets`);
